def _existing_members(ctx: AgentContext) -> dict[str, set[str]]:
    """Methods of the page objects already in the repository.

    The index records them, so a call onto a reused class can be checked rather
    than trusted. Without this a plan can reuse a real class and invent a method
    on it, which compiles in the model's head and nowhere else.
    """
    if ctx.repo_profile is None:
        return {}
    members: dict[str, set[str]] = {}
    for symbol in ctx.repo_profile.symbols_of("page_object"):
        if symbol.name:
            members[symbol.name] = set(symbol.members or [])
    return members


def _page_class_name(feature_name: str) -> str:
    name = pascal(feature_name)
    return name if name.endswith("Page") else name + "Page"


#: A Page Object name a reviewer would accept: PascalCase, not absurdly long,
#: and not obviously an echo of the prompt.
_PROMPT_ECHO = ("target", "object", "catalogue", "scenario", "existing", "verified")


def _plausible_class_name(name: str) -> bool:
    if not name or len(name) > 48 or not re.match(r"^[A-Z][A-Za-z0-9]*$", name):
        return False
    lowered = name.lower()
    return not any(token in lowered for token in _PROMPT_ECHO)


def _guess_route(ctx: AgentContext) -> str:
    if ctx.exploration and ctx.exploration.snapshots:
        for snapshot in ctx.exploration.snapshots:
            route = snapshot.route_pattern or ""
            if route and route != "/":
                return route
    title = (ctx.requirement.title if ctx.requirement else "").lower()
    slug = re.sub(r"[^a-z0-9]+", "-", title).strip("-")
    return f"/{slug}" if slug else "/"


def _normalise_step(text: str) -> str:
    """Compare step intent, ignoring keyword, parameters and punctuation."""
    stripped = re.sub(r"^(Given|When|Then|And|But|\*)\s+", "", str(text).strip(), flags=re.IGNORECASE)
    stripped = re.sub(r"\{[a-z]+\}", "", stripped)
    stripped = re.sub(r"['\"][^'\"]*['\"]", "", stripped)
    stripped = re.sub(r"<[^>]+>", "", stripped)
    return re.sub(r"[^a-z0-9]+", " ", stripped.lower()).strip()


def _relative_import(from_dir: str, to_dir: str) -> str:
    """POSIX relative import specifier between two repository directories."""
    from_parts = [p for p in from_dir.strip("/").split("/") if p]
    to_parts = [p for p in to_dir.strip("/").split("/") if p]
    common = 0
    for a, b in zip(from_parts, to_parts, strict=False):
        if a != b:
            break
        common += 1
    ups = [".."] * (len(from_parts) - common)
    downs = to_parts[common:]
    joined = "/".join(ups + downs)
    return joined if joined.startswith(".") else (f"./{joined}" if joined else ".")
