"""Code Generation Agent — plan with the model, render with code.

The naive approach asks a coding model to write whole files. Measured on a
five-scenario run that was 55% of all input tokens, on the most expensive tier,
and most of what it produced was boilerplate the platform already knows: the
import block, the class declaration, the base class, getter visibility, async
signatures, formatting.

So the division is inverted:

* **The model plans.** One call returns compact JSON — which Page Objects, which
  methods, which catalogue locator each method uses, and which Page Object
  method each Gherkin step maps to.
* **Code renders the plan.** `renderer.py` emits the TypeScript, applying the
  repository's house style.

Three wins, not one:

1. **Cost** — no boilerplate in the prompt, no file in the completion, and page
   objects and steps share a single call instead of two.
2. **Correctness** — the renderer can only emit locators from the verified
   catalogue, so a hallucinated selector is impossible by construction rather
   than detected afterwards.
3. **Consistency** — house style is applied by code, so it cannot drift between
   files or between runs.

Feature files are still rendered directly from the approved plan: the Gherkin a
human approved is byte-for-byte the Gherkin that lands.
"""

